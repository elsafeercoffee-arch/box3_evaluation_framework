def write_datasets():
    Path("data").mkdir(exist_ok=True)
    rows = []
    for qid, q, ref, kw in DIRECT:
        rows.append({"id": qid, "category": "direct", "question": q, "expected_ref": ref, "expected_answer": ART[ref], "keywords": kw, "is_answerable": True})
    for qid, q, ref, kw in COMPLEX:
        rows.append({"id": qid, "category": "complex", "question": q, "expected_ref": ref, "expected_answer": ART[ref], "keywords": kw, "is_answerable": True})
    for qid, q in TRAP:
        rows.append({"id": qid, "category": "trap", "question": q, "expected_ref": "", "expected_answer": REFUSAL, "keywords": [], "is_answerable": False})
    for qid, q in OUT_OF_SCOPE:
        rows.append({"id": qid, "category": "out_of_scope", "question": q, "expected_ref": "", "expected_answer": REFUSAL, "keywords": [], "is_answerable": False})
    with open("data/golden_eval.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open("data/human_annotations.jsonl", "w", encoding="utf-8") as f:
        for qid, ans, hc, hg, hl in HUMAN:
            f.write(json.dumps({"q_id": qid, "model_answer": ans, "human_correctness": hc, "human_groundedness": hg, "human_language": hl}, ensure_ascii=False) + "\n")
    print(f"Generated golden_eval.jsonl: {len(rows)} cases")
    print(f"Generated human_annotations.jsonl: {len(HUMAN)} samples")

if __name__ == "__main__":
    write_datasets()
